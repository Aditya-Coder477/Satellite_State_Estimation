"""
src/dataset/validator.py
========================
Provides validation routines for the generated dataset pipeline outputs.

Performs verification checks (existence, schema matching, null/inf detection,
monotonicity, split size consistency, normalization properties, and collocation
bounds) and collects all failures into a unified validation report.
"""

from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import Any, Dict, List, Tuple

import numpy as np
import pandas as pd

from src.dataset.dataset_manager import DatasetManager
from src.utils.logger import get_logger

log: logging.Logger = get_logger(__name__)


class DatasetValidator:
    """
    Validates output artifacts generated by the dataset pipeline.

    Parameters
    ----------
    cfg : Dict[str, Any]
        Project configuration.
    manager : DatasetManager
        Initialised DatasetManager instance.
    """

    def __init__(self, cfg: Dict[str, Any], manager: DatasetManager) -> None:
        self._cfg = cfg
        self._manager = manager
        self._dataset_cfg = cfg.get("dataset", {})

    def validate_all(self) -> Tuple[bool, List[str]]:
        """
        Executes all validation checks and aggregates errors.

        Returns
        -------
        Tuple[bool, List[str]]
            A tuple of (is_valid, list_of_error_messages).
        """
        log.info("Running dataset pipeline validation checks...")
        errors: List[str] = []

        # 1. Check Files Exist
        self._check_files_exist(errors)
        if errors:
            log.error("Core files are missing. Aborting further validation.")
            return False, errors

        # Load datasets for internal validation
        try:
            train_df = self._manager.load_csv(self._manager.get_dataset_path("train.csv"))
            val_df = self._manager.load_csv(self._manager.get_dataset_path("validation.csv"))
            test_df = self._manager.load_csv(self._manager.get_dataset_path("test.csv"))
            colloc_df = self._manager.load_csv(self._manager.get_dataset_path("collocation_points.csv"))
            truth_df = self._manager.load_csv(self._manager.get_input_path("truth_states_transformed.csv"))
        except Exception as e:
            errors.append(f"Failed to load dataset files for validation: {e}")
            return False, errors

        # 2. Schema Consistency Check
        self._check_schemas(train_df, val_df, test_df, errors)

        # 3. NaNs and Infs Check
        self._check_nans_infs(train_df, "train", errors)
        self._check_nans_infs(val_df, "validation", errors)
        self._check_nans_infs(test_df, "test", errors)
        self._check_nans_infs(colloc_df, "collocation_points", errors)

        # 4. Split Sizes Check
        self._check_split_sizes(len(train_df), len(val_df), len(test_df), errors)

        # 5. Chronological Order & Temporal Split Check
        self._check_chronological_splits(train_df, val_df, test_df, errors)

        # 6. Collocation Points Boundaries Check
        self._check_collocation_bounds(colloc_df, truth_df, errors)

        # 7. Normalization Parameter Consistency Check
        self._check_normalization_parameters(train_df, errors)

        # 8. Statistics Generation Check
        self._check_statistics_validity(errors)

        is_valid = len(errors) == 0
        if is_valid:
            log.info("Dataset validation passed successfully with 0 errors!")
        else:
            log.error("Dataset validation failed with %d errors.", len(errors))
            for i, err in enumerate(errors, 1):
                log.error("  Error %d: %s", i, err)

        return is_valid, errors

    def _check_files_exist(self, errors: List[str]) -> None:
        """Verifies all expected dataset pipeline files exist on disk."""
        expected_files = [
            "train.csv",
            "validation.csv",
            "test.csv",
            "collocation_points.csv",
            "normalization.json",
            "feature_statistics.json",
            "dataset_summary.json",
        ]
        for fname in expected_files:
            path = self._manager.get_dataset_path(fname)
            if not path.is_file():
                errors.append(f"Missing expected output file: {fname} (path: {path})")

    def _check_schemas(self, train: pd.DataFrame, val: pd.DataFrame, test: pd.DataFrame, errors: List[str]) -> None:
        """Verifies schemas match across train, validation, and test datasets."""
        train_cols = set(train.columns)
        val_cols = set(val.columns)
        test_cols = set(test.columns)

        if train_cols != val_cols:
            diff = train_cols.symmetric_difference(val_cols)
            errors.append(f"Schema mismatch between train and validation columns: {diff}")
        if train_cols != test_cols:
            diff = train_cols.symmetric_difference(test_cols)
            errors.append(f"Schema mismatch between train and test columns: {diff}")

    def _check_nans_infs(self, df: pd.DataFrame, name: str, errors: List[str]) -> None:
        """Verifies no NaNs or Infs are present in the numeric fields of the dataframe."""
        numeric_cols = df.select_dtypes(include=[np.number]).columns.tolist()
        
        # Check NaNs
        nan_counts = df[numeric_cols].isna().sum()
        bad_nan_cols = nan_counts[nan_counts > 0].index.tolist()
        if bad_nan_cols:
            errors.append(f"NaN values detected in '{name}' columns: {bad_nan_cols}")

        # Check Infs
        inf_counts = np.isinf(df[numeric_cols]).sum()
        bad_inf_cols = inf_counts[inf_counts > 0].index.tolist()
        if bad_inf_cols:
            errors.append(f"Inf values detected in '{name}' columns: {bad_inf_cols}")

    def _check_split_sizes(self, n_train: int, n_val: int, n_test: int, errors: List[str]) -> None:
        """Checks if the train/val/test sizes match configuration ratios approximately."""
        total = n_train + n_val + n_test
        if total == 0:
            errors.append("Empty dataset splits: sum of train, val, and test sample sizes is 0.")
            return

        split_cfg = self._dataset_cfg.get("split", {})
        expected_train = split_cfg.get("train", 0.70)
        expected_val = split_cfg.get("validation", 0.15)
        expected_test = split_cfg.get("test", 0.15)

        actual_train = n_train / total
        actual_val = n_val / total
        actual_test = n_test / total

        # Check with tolerance of 2% due to integer rounding
        tol = 0.02
        if abs(actual_train - expected_train) > tol:
            errors.append(f"Train split ratio deviation: expected {expected_train:.3f}, got {actual_train:.3f}")
        if abs(actual_val - expected_val) > tol:
            errors.append(f"Validation split ratio deviation: expected {expected_val:.3f}, got {actual_val:.3f}")
        if abs(actual_test - expected_test) > tol:
            errors.append(f"Test split ratio deviation: expected {expected_test:.3f}, got {actual_test:.3f}")

    def _check_chronological_splits(
        self, train: pd.DataFrame, val: pd.DataFrame, test: pd.DataFrame, errors: List[str]
    ) -> None:
        """Verifies that temporal splits do not overlap in time and maintain ordering."""
        strategy = self._dataset_cfg.get("split", {}).get("strategy", "temporal").lower()
        if strategy != "temporal":
            return

        t_col = "elapsed_seconds"
        if t_col not in train.columns:
            return

        # Check monotonic increase inside splits
        if not train[t_col].is_monotonic_increasing:
            errors.append("Training split time is not monotonically increasing.")
        if not val[t_col].is_monotonic_increasing:
            errors.append("Validation split time is not monotonically increasing.")
        if not test[t_col].is_monotonic_increasing:
            errors.append("Test split time is not monotonically increasing.")

        # Check separation
        train_max = train[t_col].max()
        val_min = val[t_col].min()
        val_max = val[t_col].max()
        test_min = test[t_col].min()

        if train_max > val_min:
            errors.append(f"Temporal overlap: training end time ({train_max:.1f}s) is after validation start time ({val_min:.1f}s).")
        if val_max > test_min:
            errors.append(f"Temporal overlap: validation end time ({val_max:.1f}s) is after test start time ({test_min:.1f}s).")

    def _check_collocation_bounds(self, colloc: pd.DataFrame, truth: pd.DataFrame, errors: List[str]) -> None:
        """Verifies that physics collocation times are contained within the propagation window."""
        if "time" not in colloc.columns or "elapsed_seconds" not in truth.columns:
            return

        colloc_min = colloc["time"].min()
        colloc_max = colloc["time"].max()
        truth_min = truth["elapsed_seconds"].min()
        truth_max = truth["elapsed_seconds"].max()

        # Small buffer for floating precision
        eps = 1e-3
        if colloc_min < (truth_min - eps):
            errors.append(f"Collocation points out of bounds: minimum time ({colloc_min:.2f}s) is before simulation start ({truth_min:.2f}s).")
        if colloc_max > (truth_max + eps):
            errors.append(f"Collocation points out of bounds: maximum time ({colloc_max:.2f}s) is after simulation end ({truth_max:.2f}s).")

    def _check_normalization_parameters(self, train: pd.DataFrame, errors: List[str]) -> None:
        """Performs statistical checks to confirm normalization behaves as configured."""
        norm_method = self._dataset_cfg.get("normalization", {}).get("method", "standard").lower()
        if norm_method == "identity":
            return

        norm_cols = self._dataset_cfg.get("normalization", {}).get("columns", [])
        
        # We check training dataframe because it was normalized using statistics fitted on it.
        # Mean should be close to 0 and std close to 1 for standard scaler.
        # Min should be close to 0 and max close to 1 for minmax scaler.
        for col in norm_cols:
            if col not in train.columns:
                continue

            series = train[col].dropna().astype(float)
            if len(series) < 2:
                continue

            if norm_method == "standard":
                mean_val = series.mean()
                std_val = series.std()
                if abs(mean_val) > 1e-4:
                    errors.append(f"Normalization inconsistency: column '{col}' has normalized mean = {mean_val:.6f} (expected ~0.0)")
                if abs(std_val - 1.0) > 1e-4:
                    errors.append(f"Normalization inconsistency: column '{col}' has normalized std = {std_val:.6f} (expected ~1.0)")
            
            elif norm_method == "minmax":
                min_val = series.min()
                max_val = series.max()
                if abs(min_val) > 1e-4:
                    errors.append(f"Normalization inconsistency: column '{col}' has normalized min = {min_val:.6f} (expected ~0.0)")
                if abs(max_val - 1.0) > 1e-4:
                    errors.append(f"Normalization inconsistency: column '{col}' has normalized max = {max_val:.6f} (expected ~1.0)")

    def _check_statistics_validity(self, errors: List[str]) -> None:
        """Loads and verifies that JSON statistics outputs contain expected metadata properties."""
        try:
            summary = self._manager.load_json(self._manager.get_dataset_path("dataset_summary.json"))
            if not isinstance(summary, dict) or "dataset_splits" not in summary or "temporal_range" not in summary:
                errors.append("Invalid structure in 'dataset_summary.json'.")
        except Exception as e:
            errors.append(f"Failed to load or parse 'dataset_summary.json': {e}")

        try:
            stats = self._manager.load_json(self._manager.get_dataset_path("feature_statistics.json"))
            if not isinstance(stats, dict):
                errors.append("Invalid structure in 'feature_statistics.json' (expected JSON dictionary).")
        except Exception as e:
            errors.append(f"Failed to load or parse 'feature_statistics.json': {e}")
